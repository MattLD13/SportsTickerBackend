"""Export Ticker Six weather animation frames for the Mini firmware."""
from __future__ import annotations

import argparse
from datetime import datetime, timezone
import importlib.util
import math
from pathlib import Path
import sys

from PIL import Image, ImageDraw, ImageOps

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from ticker_core.ui import weather_art

TARGET = ROOT / "esp32_hub75/src/mini/rendering/weather_art_generated.h"
ICONS = ("sun", "moon", "cloud", "rain", "snow", "fog", "storm")
WIDTH, HEIGHT, STEP_MS = 22, 17, 100


def animation_frame_count(period_seconds: float, step_ms: int) -> int:
    """Return whole frames for the shared weather animation period."""
    if period_seconds <= 0 or step_ms <= 0:
        raise ValueError("Weather period and frame step must be positive")
    frames = round(period_seconds * 1000 / step_ms)
    if frames < 1 or not math.isclose(frames * step_ms, period_seconds * 1000, rel_tol=0, abs_tol=1e-6):
        raise ValueError("Weather period must align with the Mini frame step")
    return frames


FRAMES = animation_frame_count(weather_art.ANIMATION_PERIOD, STEP_MS)


def header() -> str:
    """Fit the original artwork into one stable Mini icon rectangle."""
    unique, indices, tracks = [], {}, []
    for icon in ICONS:
        originals = []
        for index in range(FRAMES):
            image = Image.new("RGB", (48, 48))
            weather_art.draw_icon(ImageDraw.Draw(image), icon, 17, 17, index * STEP_MS / 1000)
            originals.append(image)
        bounds = [image.getbbox() for image in originals]
        box = (min(row[0] for row in bounds), min(row[1] for row in bounds),
               max(row[2] for row in bounds), max(row[3] for row in bounds))
        track = []
        for original in originals:
            image = ImageOps.pad(original.crop(box), (WIDTH, HEIGHT), method=Image.Resampling.NEAREST, color=(0, 0, 0))
            pixels = tuple(((r & 248) << 8) | ((g & 252) << 3) | (b >> 3) for r, g, b in image.getdata())
            if pixels not in indices:
                indices[pixels] = len(unique)
                unique.append(pixels)
            track.append(indices[pixels])
        tracks.append(track)
    lines = ["// Generated by tools/mini/generate_mini_weather.py from Ticker Six weather artwork.",
             "#pragma once", "#include <stdint.h>", "namespace mini_weather_art {",
             f"static constexpr int Width = {WIDTH}, Height = {HEIGHT}, Frames = {FRAMES}, StepMs = {STEP_MS};",
             f"static constexpr uint16_t Pixels[{len(unique)}][Width * Height] = {{"]
    lines += ["  {" + ",".join(map(str, pixels)) + "}," for pixels in unique]
    lines += ["};", "// Track order: sun, moon, cloud, rain, snow, fog, storm.", "static constexpr uint16_t Tracks[7][Frames] = {"]
    lines += ["  {" + ",".join(map(str, track)) + "}," for track in tracks]
    lines += ["};", "}  // namespace mini_weather_art", ""]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    source = header()
    if args.check:
        if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != source:
            raise SystemExit("Mini weather artwork differs. Run tools/mini/generate_mini_weather.py.")
        print("Mini weather animation matches Ticker Six artwork.")
    else:
        TARGET.write_text(source, encoding="utf-8")
        print(TARGET)


if __name__ == "__main__":
    main()

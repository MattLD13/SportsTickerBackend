"""Generate the Mini JSON filter from the backend wire contract."""
import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from sports_ticker.projections.mini_fields import payload_filter

TARGET = ROOT / "ticker-mini/src/mini/protocol/fields_generated.h"


def header():
    specification = json.dumps(payload_filter(), separators=(",", ":"), sort_keys=True)
    return '// Generated by tools/mini/generate_mini_fields.py. Edit the backend Mini field owner.\n#pragma once\nstatic constexpr char MINI_PAYLOAD_FILTER[] = R"fields(' + specification + ')fields";\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = header()
    if args.check:
        if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != expected:
            raise SystemExit("Generated Mini fields differ from the backend contract")
    else:
        TARGET.write_text(expected, encoding="utf-8")


if __name__ == "__main__":
    main()

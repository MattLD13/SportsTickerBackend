"""Export the main ticker glyphs and colors for the Mini firmware."""
from __future__ import annotations

import argparse
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
from ticker.six.ui.text import PANE, HYBRID
from ticker.six.ui import palette
from ticker.shared.leagues import LEAGUES
from ticker.shared.sports_display import sport_family

TARGET = Path(__file__).resolve().parents[2] / "mini/src/mini/ui/generated.h"


def header() -> str:
    """Return deterministic C++ data from the main ticker drawing owners."""
    lines = ["// Generated by tools/mini/generate_mini_ui.py. Edit the Python drawing owners.",
             "#pragma once", "#include <stdint.h>", "#include <string.h>", "namespace mini_ui {",
             "struct Rgb { uint8_t r, g, b; };"]
    for name, value in vars(palette).items():
        if name.isupper() and isinstance(value, int):
            lines.append(f"static constexpr uint8_t {name} = {value};")
        elif name.isupper():
            lines.append(f"static constexpr Rgb {name} = {{{value[0]}, {value[1]}, {value[2]}}};")
    for name, mapping, height in (("pane", PANE, 5), ("hybrid", HYBRID, 6)):
        lines.append(f"static constexpr uint8_t {name}[95][{height}] = {{")
        for code in range(32, 127):
            glyph = mapping.get(chr(code), mapping[" "])
            if name == "pane" and (len(glyph) != height or not 1 <= len(glyph[0]) <= 8 or any(len(row) != len(glyph[0]) for row in glyph)):
                raise ValueError(f"PANE glyph {chr(code)!r} must contain consistent rows of one to eight columns")
            rows = [sum(int(bit) << (len(row)-1-index) for index, bit in enumerate(row)) for row in glyph] if name == "pane" else glyph
            lines.append("  {" + ", ".join(map(str, rows)) + "},")
        lines.append("};")
        if name == "pane":
            widths = [str(len(mapping.get(chr(code), mapping[" "])[0])) for code in range(32, 127)]
            lines.append("static constexpr uint8_t paneWidths[95] = {" + ", ".join(widths) + "};")
    for name, glyph in (("inningTop", PANE["▲"]), ("inningBottom", PANE["▼"])):
        rows = [sum(bit << (2-index) for index, bit in enumerate(row)) for row in glyph]
        lines.append(f"static constexpr uint8_t {name}[5] = {{" + ", ".join(map(str, rows)) + "};")
    lines += ["inline const char* sportFamily(const char* league) {"]
    identifiers = sorted({league.id for league in LEAGUES} | {"football", "baseball", "basketball", "hockey", "soccer"})
    for identifier in identifiers:
        lines.append(f'  if (strcmp(league, "{identifier}") == 0) return "{sport_family(identifier)}";')
    lines += ['  return "other";', "}", "}  // namespace mini_ui", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    result = header()
    if args.check:
        if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != result:
            raise SystemExit("Mini drawing data differs. Run tools/mini/generate_mini_ui.py.")
        print("Mini drawing data matches the main ticker.")
    else:
        TARGET.write_text(result, encoding="utf-8")
        print(TARGET)
